-- 瞬时日语 / Supabase 初始化脚本
create extension if not exists pgcrypto;
create table if not exists public.profiles(id uuid primary key references auth.users(id) on delete cascade, username text not null unique, role text not null default 'user' check(role in ('user','admin')), created_at timestamptz not null default now());
create table if not exists public.vocabularies(id uuid primary key default gen_random_uuid(), name text not null unique, type text not null check(type in ('public','private')), owner_id uuid references auth.users(id) on delete cascade, created_at timestamptz not null default now());
create table if not exists public.words(id uuid primary key default gen_random_uuid(), vocabulary_id uuid not null references public.vocabularies(id) on delete cascade, w text not null, r text not null default '', m text not null default '', position integer not null default 0, unique(vocabulary_id,w,r));
create table if not exists public.wrong_words(user_id uuid not null references auth.users(id) on delete cascade, vocabulary_id uuid not null references public.vocabularies(id) on delete cascade, w text not null, r text not null default '', m text not null default '', count integer not null default 1, updated_at timestamptz not null default now(), primary key(user_id,vocabulary_id,w,r));
create table if not exists public.study_stats(user_id uuid not null references auth.users(id) on delete cascade, study_date date not null, opens integer not null default 0, quizzed integer not null default 0, wrong integer not null default 0, last_report text, primary key(user_id,study_date));
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$ select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'); $$;
revoke all on function public.is_admin() from public; grant execute on function public.is_admin() to authenticated;
drop policy if exists profiles_self on public.profiles; create policy profiles_self on public.profiles for select to authenticated using(id=auth.uid());
drop policy if exists vocab_read on public.vocabularies; create policy vocab_read on public.vocabularies for select to authenticated using(type='public' or owner_id=auth.uid());
drop policy if exists vocab_insert on public.vocabularies; create policy vocab_insert on public.vocabularies for insert to authenticated with check((type='private' and owner_id=auth.uid()) or (type='public' and public.is_admin()));
drop policy if exists vocab_update on public.vocabularies; create policy vocab_update on public.vocabularies for update to authenticated using((type='private' and owner_id=auth.uid()) or public.is_admin()) with check((type='private' and owner_id=auth.uid()) or public.is_admin());
drop policy if exists vocab_delete on public.vocabularies; create policy vocab_delete on public.vocabularies for delete to authenticated using((type='private' and owner_id=auth.uid()) or public.is_admin());
drop policy if exists words_read on public.words; create policy words_read on public.words for select to authenticated using(exists(select 1 from public.vocabularies v where v.id=vocabulary_id and (v.type='public' or v.owner_id=auth.uid())));
drop policy if exists words_write on public.words; create policy words_write on public.words for all to authenticated using(exists(select 1 from public.vocabularies v where v.id=vocabulary_id and ((v.type='private' and v.owner_id=auth.uid()) or public.is_admin()))) with check(exists(select 1 from public.vocabularies v where v.id=vocabulary_id and ((v.type='private' and v.owner_id=auth.uid()) or public.is_admin())));
drop policy if exists wrong_self on public.wrong_words; create policy wrong_self on public.wrong_words for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
drop policy if exists stats_self on public.study_stats; create policy stats_self on public.study_stats for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
alter table public.profiles enable row level security; alter table public.vocabularies enable row level security; alter table public.words enable row level security; alter table public.wrong_words enable row level security; alter table public.study_stats enable row level security;
